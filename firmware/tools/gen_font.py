#!/usr/bin/env python3
"""Generates an LVGL 9 font (lv_font_fmt_txt, 4 bpp, no compression) from a TTF with Pillow.

Used for the big room temperature: LVGL's built-in Montserrat stops at 48 px, and scaling a 48 px label up
blurs it. This renders the few glyphs needed at their real size instead.

  python3 tools/gen_font.py SIZE NAME CHARS OUT.c
  python3 tools/gen_font.py 76 font_room_76 " -.0123456789°" main/font_room_76.c
"""
import sys
from PIL import Image, ImageDraw, ImageFont

TTF = "managed_components/lvgl__lvgl/scripts/generators/built_in_font/Montserrat-Medium.ttf"


def main():
    size, name, chars, out = int(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4]
    font = ImageFont.truetype(TTF, size)
    ascent, descent = font.getmetrics()
    codes = sorted(set(ord(c) for c in chars))

    bitmap = bytearray()
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */"]
    for cp in codes:
        ch = chr(cp)
        adv = round(font.getlength(ch) * 16)
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(r - l, 0), max(b - t, 0)
        start = len(bitmap)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            px = img.load()
            nib = [px[x, y] >> 4 for y in range(h) for x in range(w)]  # rows packed continuously
            if len(nib) % 2:
                nib.append(0)
            bitmap += bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        else:
            w = h = 0
        dsc.append(f"    {{.bitmap_index = {start}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, "
                   f".ofs_x = {l if w else 0}, .ofs_y = {-b if h else 0}}} /* U+{cp:04X} */")

    # One cmap per run of consecutive code points
    runs, gid = [], 1
    for cp in codes:
        if runs and cp == runs[-1][0] + runs[-1][1]:
            runs[-1][1] += 1
        else:
            runs.append([cp, 1, gid])
        gid += 1
    cmaps = ",\n".join(
        f"    {{.range_start = {s}, .range_length = {n}, .glyph_id_start = {g}, .unicode_list = NULL, "
        f".glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}"
        for s, n, g in runs)

    rows = [", ".join(f"0x{v:02x}" for v in bitmap[i:i + 16]) for i in range(0, len(bitmap), 16)]
    with open(out, "w") as f:
        f.write(f"""// Generated by tools/gen_font.py: Montserrat Medium {size} px, 4 bpp, glyphs {chars!r}.
// Do not edit; regenerate instead.
#include "lvgl.h"

static const uint8_t glyph_bitmap[] = {{
    {(","+chr(10)+"    ").join(rows)}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(","+chr(10)).join(dsc)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
{cmaps}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(runs)},
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = {-round(size / 12)},
    .underline_thickness = {max(1, round(size / 24))},
    .static_bitmap = 1,
    .dsc = &font_dsc,
    .fallback = NULL,
    .user_data = NULL,
}};
""")
    print(f"{out}: {len(codes)} glyphs, {len(bitmap)} bytes, line height {ascent + descent}")


if __name__ == "__main__":
    main()
